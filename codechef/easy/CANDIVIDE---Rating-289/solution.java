import java.util.*;
import java.lang.*;
import java.io.*;

class Codechef
{
	public static void main (String[] args) throws java.lang.Exception
	{
	Scanner scanner = new Scanner(System.in);
	int t=scanner.nextInt();
	
	for(int i=0;i<t;i++)
	{
	 int candy=scanner.nextInt();
	 if(candy%3==0)
	 {
	     System.out.println("YES");
	 }else{
	     System.out.println("NO");
	 }
	 
	}
	}
}
